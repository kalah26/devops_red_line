export function applyNagSuppressions(app: App, account: string, region: string, bedrockModelId: string): void {
  const byPath = new Map<string, IConstruct>(app.node.findAll().map((c) => [c.node.path, c]));
  for (const [path, acks] of Object.entries(accepted(account, region, bedrockModelId))) {
    const construct = byPath.get(path);
    if (!construct) throw new Error(`cdk-nag suppression target not found: ${path}`);
    Validations.of(construct).acknowledge(...acks);
  }
}
